let currentLang = 'en';

function setLanguage(lang) {
    // keep the timeline strip's accessible name in sync (script.js template re-render runs only on button toggle)
    currentLang = lang;
    document.documentElement.setAttribute('lang', lang);
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key]) {
            el.innerHTML = translations[lang][key];
        }
    });

    // Update skills manually (index page only)
    const skillsList = document.getElementById('skills-list');
    if (skillsList) {
        skillsList.innerHTML = '';
        translations[lang].skills.forEach(skill => {
            const li = document.createElement('li');
            li.className = 'terminal-text small';
            li.innerText = skill;
            skillsList.appendChild(li);
        });
    }

    const langBtn = document.getElementById('lang-toggle');
    if (langBtn) {
        langBtn.innerText = `[ ${lang.toUpperCase()} ]`;
    }

    // Theme button + nav aria-label are also translated
    if (window.updateThemeText) window.updateThemeText();
    if (window.updateNavAria) window.updateNavAria();
    const tlAria = document.querySelector('.timeline-slider');
    if (tlAria) tlAria.setAttribute('aria-label', translations[lang].timeline_aria || tlAria.getAttribute('aria-label') || '');
}
